import { APP_PERMISSIONS } from "../../../../constants/rbac.js";
import {
  requireAdmin,
  requireAnyPermission,
  requirePermission,
  protectedRoute,
} from "../../../identity/api/http/auth.middleware.js";
import {
  deleteUserAsAdmin,
  getBlockDetail,
  getBlockedUsers,
  getBlocks,
  getConversationDetail,
  getConversations,
  getDashboardMessageChart,
  getDashboardOverview,
  getDashboardReportChart,
  getDashboardStats,
  getDashboardSupportChart,
  getDashboardUserChart,
  getFriendRequestsAdmin,
  getFriendships,
  getMaintenanceInfo,
  getMessages,
  getReportDetail,
  getReports,
  getSystemHealth,
  getUserDetail,
  getUsers,
  requestMaintenancePasswordVerification,
  resolveReportWithAction,
  unblockBlockRelationAsAdmin,
  updateMaintenanceMessage,
  updateReportStatus,
  updateUserStatus,
  verifyMaintenancePassword,
  confirmMaintenanceToggle,
} from "./admin.controller.js";
import {
  getAdminAuditLogs,
  getAdminRoles,
  getAdminUserPermissions,
  patchAdminUserRoles,
} from "./admin-role.controller.js";
import { createRouteModule, defineRoute } from "../../../../shared/api/http/route-adapter.js";


// Khai báo tất cả các route của admin panel ở đây, bao gồm cả middleware bảo vệ và phân quyền
export default createRouteModule({
  routerMiddlewares: [protectedRoute, requireAdmin],
  routes: [
    defineRoute(
      "get",
      "/dashboard/overview",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardOverview,
    ),
    defineRoute(
      "get",
      "/dashboard/charts/users",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardUserChart,
    ),
    defineRoute(
      "get",
      "/dashboard/charts/messages",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardMessageChart,
    ),
    defineRoute(
      "get",
      "/dashboard/charts/reports",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardReportChart,
    ),
    defineRoute(
      "get",
      "/dashboard/charts/support",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardSupportChart,
    ),
    defineRoute(
      "get",
      "/dashboard",
      requirePermission(APP_PERMISSIONS.DASHBOARD_VIEW),
      getDashboardStats,
    ),
    defineRoute(
      "get",
      "/roles",
      requirePermission(APP_PERMISSIONS.ROLE_VIEW),
      getAdminRoles,
    ),
    defineRoute(
      "get",
      "/audit-logs",
      requirePermission(APP_PERMISSIONS.AUDIT_LOG_VIEW),
      getAdminAuditLogs,
    ),
    defineRoute(
      "get",
      "/users",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getUsers,
    ),
    defineRoute(
      "get",
      "/users/:id/permissions",
      requirePermission(APP_PERMISSIONS.PERMISSION_VIEW),
      getAdminUserPermissions,
    ),
    defineRoute(
      "get",
      "/users/:id",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getUserDetail,
    ),
    defineRoute(
      "patch",
      "/users/:id/status",
      requireAnyPermission([
        APP_PERMISSIONS.USER_LOCK,
        APP_PERMISSIONS.USER_UNLOCK,
      ]),
      updateUserStatus,
    ),
    defineRoute(
      "patch",
      "/users/:id/roles",
      requirePermission(APP_PERMISSIONS.ROLE_ASSIGN),
      patchAdminUserRoles,
    ),
    defineRoute(
      "patch",
      "/users/:userId/role",
      requirePermission(APP_PERMISSIONS.ROLE_ASSIGN),
      patchAdminUserRoles,
    ),
    defineRoute(
      "delete",
      "/users/:id",
      requirePermission(APP_PERMISSIONS.USER_DELETE),
      deleteUserAsAdmin,
    ),
    defineRoute(
      "get",
      "/friends",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getFriendships,
    ),
    defineRoute(
      "get",
      "/friend-requests",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getFriendRequestsAdmin,
    ),
    defineRoute(
      "get",
      "/conversations",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getConversations,
    ),
    defineRoute(
      "get",
      "/conversations/:id",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getConversationDetail,
    ),
    defineRoute(
      "get",
      "/messages",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getMessages,
    ),
    defineRoute(
      "get",
      "/blocks",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getBlocks,
    ),
    defineRoute(
      "get",
      "/blocks/:id",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getBlockDetail,
    ),
    defineRoute(
      "patch",
      "/blocks/:id/unblock",
      requireAnyPermission([
        APP_PERMISSIONS.USER_UNLOCK,
        APP_PERMISSIONS.USER_LOCK,
      ]),
      unblockBlockRelationAsAdmin,
    ),
    defineRoute(
      "get",
      "/blocked-users",
      requirePermission(APP_PERMISSIONS.USER_VIEW),
      getBlockedUsers,
    ),
    defineRoute(
      "get",
      "/reports",
      requirePermission(APP_PERMISSIONS.REPORT_VIEW),
      getReports,
    ),
    defineRoute(
      "get",
      "/reports/:id",
      requirePermission(APP_PERMISSIONS.REPORT_VIEW),
      getReportDetail,
    ),
    defineRoute(
      "patch",
      "/reports/:id/status",
      requirePermission(APP_PERMISSIONS.REPORT_HANDLE),
      updateReportStatus,
    ),
    defineRoute(
      "patch",
      "/reports/:id/resolve-with-action",
      requirePermission(APP_PERMISSIONS.REPORT_HANDLE),
      resolveReportWithAction,
    ),
    defineRoute("get", "/health", getSystemHealth),
    defineRoute(
      "get",
      "/maintenance/status",
      requirePermission(APP_PERMISSIONS.MAINTENANCE_TOGGLE),
      getMaintenanceInfo,
    ),
    defineRoute(
      "post",
      "/maintenance/request-verification",
      requirePermission(APP_PERMISSIONS.MAINTENANCE_TOGGLE),
      requestMaintenancePasswordVerification,
    ),
    defineRoute(
      "post",
      "/maintenance/verify-password",
      requirePermission(APP_PERMISSIONS.MAINTENANCE_TOGGLE),
      verifyMaintenancePassword,
    ),
    defineRoute(
      "post",
      "/maintenance/confirm-toggle",
      requirePermission(APP_PERMISSIONS.MAINTENANCE_TOGGLE),
      confirmMaintenanceToggle,
    ),
    defineRoute(
      "patch",
      "/maintenance/message",
      requirePermission(APP_PERMISSIONS.MAINTENANCE_TOGGLE),
      updateMaintenanceMessage,
    ),
  ],
});
